"""Emit Rust highlight tables + engine-input model from parsed Text_Highlighter data.

Reads tables_<LANG>.json (see parse_tables.py) and writes
src/render/html/element/highlight_tables.rs for the PEAR Text_Highlighter
snapshot Wikidot vendors. Custom (non-portable) alternatives become
never-matching placeholders with identical group counts; the engine
implements them by custom id (see highlight.rs). Keyword groups that
upstream disables by default (its _conditions, evaluated with no defines
supplied) are recorded in HlLang::disabled.

Usage: emit_tables.py --tables-dir DIR --out highlight_tables.rs
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import codegen as C

LANGS = ['PHP', 'HTML', 'JAVASCRIPT', 'XML', 'SQL', 'CPP', 'DIFF',
         'RUBY', 'PERL', 'PYTHON', 'JAVA', 'CSS', 'DTD']


def convert_pattern(pat):
    # PCRE (ASCII, no /u) -> Rust regex. The patterns are near-compatible;
    # only repeated flags need folding, plus `.` (any byte but newline in
    # PCRE-without-/s, which the `regex` crate rejects on `str` haystacks)
    # becomes an explicit non-newline scalar class.
    pat = pat.replace('(?ii)', '(?i)')
    # Upstream occasionally emits doubled flags (`(?mii)`); PCRE tolerates
    # them but Rust rejects duplicates, so deduplicate flag letters.
    import re as _re
    def _dedup(m):
        seen = ''
        for ch in m.group(1):
            if ch not in seen:
                seen += ch
        return '(?' + seen + ')'
    pat = _re.sub(r'\(\?([imsx]+)\)', _dedup, pat)
    out = []
    i, n = 0, len(pat)
    cc = False
    while i < n:
        ch = pat[i]
        if cc:
            out.append(ch)
            if ch == '\\' and i + 1 < n:
                # Escaped pairs (including `\]`) never close the class.
                out.append(pat[i + 1])
                i += 2
                continue
            if ch == ']':
                cc = False
            i += 1
            continue
        if ch == '\\' and i + 1 < n:
            nxt = pat[i + 1]
            if nxt == '<' or nxt == '>':
                # PCRE `\<`/`\>` are literal angle brackets, but the Rust
                # `regex` crate reads them as word-boundary assertions.
                # Emit the bare bracket instead (no escaping needed).
                out.append(nxt)
            else:
                out.append(ch)
                out.append(nxt)
            i += 2
            continue
        if ch == '[':
            cc = True
            out.append(ch)
            i += 1
            continue
        if ch == '.':
            out.append('[^\\n]')
            i += 1
            continue
        out.append(ch)
        i += 1
    return ''.join(out)


def placeholder(groups):
    # Never-matching alternative preserving the wrapped group count.
    assert groups >= 1
    return '(' + '($^)' * (groups - 1) + ')' if groups > 1 else '($^)'


CUSTOM_VARIANT = {
    'py_funcname': 'PyFuncname',
    'css_selector': 'CssSelector',
    'dtd_tagname': 'DtdTagname',
    'html_tagname': 'HtmlTagname',
    'perl_qqw': 'PerlQqw',
    'perl_q': 'PerlQ',
    'perl_subst2': 'PerlSubst2',
    'perl_subst1': 'PerlSubst1',
}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tables-dir', required=True)
    parser.add_argument('--out', required=True)
    args = parser.parse_args()

    out = []
    out.append('// @generated by misc/highlight-tables/emit_tables.py from the PEAR')
    out.append('// Text_Highlighter generated classes Wikidot vendors (upstream')
    out.append('// commit 0fab9c0, 2007-06-03); see misc/highlight-tables/README.md.')
    out.append('// DO NOT EDIT: regenerate with that script.')
    out.append('')
    for lang in LANGS:
        t = json.load(open(os.path.join(args.tables_dir, 'tables_%s.json' % lang)))
        regs = t['_regs']
        counts = t['_counts']
        states = t['_states']
        delim = t['_delim']
        inner = t['_inner']
        end = t['_end']
        subst = t['_subst']
        parts = t['_parts']
        kw = t['_keywords']
        out.append('pub mod %s {' % lang.lower())
        out.append('    use super::super::{HlEnd, HlRule, HlCustom, HlCustomEnd, HlLang};')
        out.append('')
        out.append('    pub static LANG: HlLang = HlLang {')
        out.append('        def_class: %s,' % rust_str(t['_defClass']))
        out.append('        kwmap: &[')
        _kwmap = t['_kwmap'] or {}
        _kwmap = _kwmap if isinstance(_kwmap, dict) else {}
        for g, cls in _kwmap.items():
            out.append('            (%s, %s),' % (rust_str(g), rust_str(cls)))
        out.append('        ],')
        # Disabled keyword groups. Upstream evaluates Text_Highlighter's
        # _conditions with an empty defines list (FTML passes none), so every
        # condition action with the invert flag set leaves its group disabled.
        # PHP numeric arrays arrive as dicts with string keys, hence the
        # reordering below (java.builtins is the only such condition).
        def php_list(value):
            if isinstance(value, dict):
                return [value[k] for k in sorted(value, key=int)]
            return value or []

        disabled = set()
        for _cond, actions in (t.get('_conditions') or {}).items():
            for action in php_list(actions):
                action = php_list(action)
                if len(action) == 2 and action[1] is True:
                    disabled.add(action[0])
        out.append('        disabled: &[%s],' % ', '.join(rust_str(d) for d in sorted(disabled)))
        out.append('        ends: &[')
        for st in sorted(end.keys(), key=int):
            e = end[st]
            cust = None
            for clang, cstate, sub, cid in C.CUSTOM_ENDS:
                if clang == lang and (cstate is None or cstate == st) and sub in e:
                    cust = cid
                    break
            if cust:
                out.append('            (%s, HlEnd::Custom(HlCustomEnd::%s)),' % (st, {'cpp_line_end': 'CppLineEnd', 'php_code_end': 'PhpCodeEnd', 'diff_norm_end': 'DiffNormEnd', 'css_prop_end': 'CssPropEnd'}[cust]))
            else:
                out.append('            (%s, HlEnd::Pattern(%s)),' % (st, rust_str(convert_pattern(strip_slashes(e)))))
        out.append('        ],')
        out.append('        states: &[')
        for st in sorted(regs.keys(), key=int):
            alts = C.split_alt(regs[st])
            out.append('            (%s, &[' % st)
            for i, a in enumerate(alts):
                # Detect custom (non-portable) alternatives on the raw PCRE
                # source: conversion rewrites `\<`/`\>` which some
                # signatures key on.
                cid = C.alt_needs_custom(lang, st, a)
                dead = C.alt_is_dead(lang, a)
                si = str(i)
                if cid:
                    pat = placeholder(counts[st][si] + 1)
                    custom = 'HlCustom::%s' % CUSTOM_VARIANT[cid]
                elif dead:
                    # See DEAD_RULES: the rule cannot fire in the deployed
                    # combined alternation, so emit a never-matching
                    # placeholder with identical group count.
                    pat = placeholder(counts[st][si] + 1)
                    custom = 'HlCustom::None'
                else:
                    pat = convert_pattern(a)
                    custom = 'HlCustom::None'
                p = parts.get(st)
                parts_src = 'None'
                pp = p.get(si) if p else None
                if isinstance(pp, dict) and pp:
                    items = ', '.join('(%s, %s)' % (g, rust_str(c)) for g, c in pp.items())
                    parts_src = 'Some(&[%s])' % items
                k = kw.get(st) or {}
                kw_src = 'None'
                kk = k.get(si) if k else None
                if isinstance(kk, dict) and kk:
                    items = ', '.join('(%s, %s)' % (rust_str(g), rust_str(pat2)) for g, pat2 in kk.items())
                    kw_src = 'Some(&[%s])' % items
                out.append('                HlRule { pattern: %s, groups: %s,' % (rust_str(pat), counts[st][si] + 1))
                out.append('                    custom: %s,' % custom)
                out.append('                    target: %s, remember: %s,' % (states[st][si], 'true' if subst[st][si] else 'false'))
                out.append('                    delim: %s, inner: %s,' % (rust_str(delim[st][si]), rust_str(inner[st][si])))
                out.append('                    parts: %s, keywords: %s },' % (parts_src, kw_src))
            out.append('            ]),')
        out.append('        ],')
        out.append('    };')
        out.append('}')
        out.append('')
    with open(args.out, 'w') as f:
        f.write('\n'.join(out))
    print('wrote', args.out)


def strip_slashes(s):
    assert s.startswith('/') and s.endswith('/'), s[:60]
    return s[1:-1]


def rust_str(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


if __name__ == '__main__':
    main()
